import { randomBytes } from "node:crypto";
import { access, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { resolve } from "node:path";

const target = resolve(process.cwd(), ".env.local");

try {
  await access(target, constants.F_OK);
  console.log(".env.local already exists; nothing was changed.");
  process.exit(0);
} catch {
  // The local environment file does not exist yet.
}

const secret = (bytes = 32) => randomBytes(bytes).toString("base64url");
const adminPassword = secret(24);
const memberPassword = secret(24);

const contents = `# Generated by npm run env:setup. Never commit this file.
DIRECTUS_URL=http://127.0.0.1:8056
NEXT_PUBLIC_DIRECTUS_URL=http://127.0.0.1:8056
APP_URL=http://localhost:3001
NEXT_PUBLIC_APP_URL=http://localhost:3001
AUTH_COOKIE_SECURE=false
AUTH_RATE_LIMIT_TRUST_PROXY=false
REGISTRATION_ENABLED=true
NEXT_PUBLIC_TURNSTILE_SITE_KEY=1x00000000000000000000AA
TURNSTILE_SECRET_KEY=1x0000000000000000000000000000000AA
GOOGLE_SSO_AUTH_URL=
X_SSO_AUTH_URL=
PMC_WEBSITE_PUBLIC_URL=http://localhost:3001
DISCORD_ARTICLE_WEBHOOK_URL=
DIRECTUS_EMAIL_FROM=no-reply@pmc-website.local
MAILPIT_UI_PORT=8026

DIRECTUS_DEV_PORT=8056
DIRECTUS_DEV_SECRET=${secret(48)}
DIRECTUS_DEV_ADMIN_EMAIL=admin@example.com
DIRECTUS_DEV_ADMIN_PASSWORD=${adminPassword}
DIRECTUS_DEV_MEMBER_EMAIL=member@example.com
DIRECTUS_DEV_MEMBER_PASSWORD=${memberPassword}
DIRECTUS_DEV_DB_PASSWORD=${secret(32)}

DIRECTUS_RATE_LIMITER_POINTS=1000
DIRECTUS_RATE_LIMITER_DURATION=60
DIRECTUS_REGISTRATION_RATE_LIMIT_POINTS=5
DIRECTUS_REGISTRATION_RATE_LIMIT_DURATION=3600

MAX_IMAGE_UPLOAD_BYTES=8388608
MAX_IMAGE_INPUT_PIXELS=40000000
`;

await writeFile(target, contents, { encoding: "utf8", flag: "wx", mode: 0o600 });

console.log("Created .env.local with generated local-only credentials.");
console.log("Directus admin:  admin@example.com");
console.log(`Admin password:  ${adminPassword}`);
console.log("Directus member: member@example.com");
console.log(`Member password: ${memberPassword}`);
